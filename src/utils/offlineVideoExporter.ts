/** Yields a macrotask so the page can repaint progress (MessageChannel is not throttled in background tabs). */
function yieldToEventLoop(): Promise<void> {
  return new Promise((resolve) => {
    const channel = new MessageChannel();
    channel.port1.onmessage = () => resolve();
    channel.port2.postMessage(null);
  });
}

/**
 * Surgical binary duration patcher for MP4 (ISOBMFF / fragmented MP4) files
 * generated by browser MediaRecorder live streaming.
 */
export async function safeFixMp4(
  rawBlob: Blob,
  targetDurationSec?: number
): Promise<Blob> {
  if (rawBlob.size < 32 || !targetDurationSec || targetDurationSec <= 0) {
    return rawBlob;
  }

  try {
    const arrayBuffer = await rawBlob.arrayBuffer();
    const u8 = new Uint8Array(arrayBuffer);
    const view = new DataView(u8.buffer, u8.byteOffset, u8.byteLength);

    function readBoxHeader(offset: number): { size: number; type: string; headerSize: number } | null {
      if (offset + 8 > u8.length) return null;
      let size = view.getUint32(offset);
      const type = String.fromCharCode(
        u8[offset + 4],
        u8[offset + 5],
        u8[offset + 6],
        u8[offset + 7]
      );
      let headerSize = 8;
      if (size === 1) {
        if (offset + 16 > u8.length) return null;
        const high = view.getUint32(offset + 8);
        const low = view.getUint32(offset + 12);
        size = high * 4294967296 + low;
        headerSize = 16;
      } else if (size === 0) {
        size = u8.length - offset;
      }
      return { size, type, headerSize };
    }

    let movieTimescale = 1000;
    let patchedCount = 0;
    const searchLimit = Math.min(u8.length, 4 * 1024 * 1024);

    function walkBoxes(start: number, end: number) {
      let pos = start;
      while (pos + 8 <= end) {
        const box = readBoxHeader(pos);
        if (!box || box.size < 8) break;
        const boxEnd = Math.min(end, pos + box.size);

        if (box.type === 'moov' || box.type === 'trak' || box.type === 'mdia' || box.type === 'mvex') {
          walkBoxes(pos + box.headerSize, boxEnd);
        } else if (box.type === 'mvhd') {
          const version = u8[pos + 8];
          const timescaleOffset = pos + 8 + 4 + (version === 1 ? 16 : 8);
          if (timescaleOffset + 8 <= boxEnd) {
            movieTimescale = view.getUint32(timescaleOffset) || 1000;
            const durOffset = timescaleOffset + 4;
            const durVal = Math.round(targetDurationSec! * movieTimescale);
            if (version === 1) {
              view.setUint32(durOffset, Math.floor(durVal / 4294967296));
              view.setUint32(durOffset + 4, durVal >>> 0);
            } else {
              view.setUint32(durOffset, durVal >>> 0);
            }
            patchedCount++;
          }
        } else if (box.type === 'tkhd') {
          const version = u8[pos + 8];
          const durOffset = pos + 8 + 4 + (version === 1 ? 16 : 8) + 8;
          if (durOffset + (version === 1 ? 8 : 4) <= boxEnd) {
            const durVal = Math.round(targetDurationSec! * movieTimescale);
            if (version === 1) {
              view.setUint32(durOffset, Math.floor(durVal / 4294967296));
              view.setUint32(durOffset + 4, durVal >>> 0);
            } else {
              view.setUint32(durOffset, durVal >>> 0);
            }
            patchedCount++;
          }
        } else if (box.type === 'mdhd') {
          const version = u8[pos + 8];
          const timescaleOffset = pos + 8 + 4 + (version === 1 ? 16 : 8);
          if (timescaleOffset + 8 <= boxEnd) {
            const mediaTimescale = view.getUint32(timescaleOffset) || movieTimescale;
            const durOffset = timescaleOffset + 4;
            const durVal = Math.round(targetDurationSec! * mediaTimescale);
            if (version === 1) {
              view.setUint32(durOffset, Math.floor(durVal / 4294967296));
              view.setUint32(durOffset + 4, durVal >>> 0);
            } else {
              view.setUint32(durOffset, durVal >>> 0);
            }
            patchedCount++;
          }
        } else if (box.type === 'mehd') {
          const version = u8[pos + 8];
          const durOffset = pos + 8 + 4;
          if (durOffset + (version === 1 ? 8 : 4) <= boxEnd) {
            const durVal = Math.round(targetDurationSec! * movieTimescale);
            if (version === 1) {
              view.setUint32(durOffset, Math.floor(durVal / 4294967296));
              view.setUint32(durOffset + 4, durVal >>> 0);
            } else {
              view.setUint32(durOffset, durVal >>> 0);
            }
            patchedCount++;
          }
        }

        pos = boxEnd;
      }
    }

    walkBoxes(0, searchLimit);

    if (patchedCount > 0) {
      return new Blob([u8], { type: rawBlob.type || 'video/mp4' });
    }
    return rawBlob;
  } catch (err) {
    console.warn('[safeFixMp4] Binary patch note:', err);
    return rawBlob;
  }
}

/** Resolves the highest supported H.264 WebCodecs framerate (falls back from 60fps to 30fps if needed). */
export async function resolveOfflineVideoCapability(
  aspect: RecordAspectRatio,
  quality: RecordQualityPreset
): Promise<{ supported: boolean; fps: number }> {
  if (typeof VideoEncoder === 'undefined' || typeof VideoFrame === 'undefined') {
    return { supported: false, fps: 30 };
  }
  const dims = getRecordingDimensions(aspect, quality);
  const candidates = dims.offlineFps > 30 ? [dims.offlineFps, 30] : [dims.offlineFps];
  for (const fps of candidates) {
    try {
      const ok = await canEncodeVideo('avc', {
        width: dims.exportWidth,
        height: dims.exportHeight,
        frameRate: fps,
        quality: new Quality({ bitrate: dims.offlineBitrate }),
      });
      if (ok) {
        return { supported: true, fps };
      }
    } catch {
      // try lower candidate
    }
  }
  return { supported: false, fps: 30 };
}

async function openDecodedFrameSource(
  blob: Blob,
  coverWidth: number,
  coverHeight: number
): Promise<VideoFrameSource | null> {
  const input = new Input({ source: new BlobSource(blob), formats: ALL_FORMATS });
  try {
    const track = await input.getPrimaryVideoTrack();
    if (!track || !(await track.canDecode())) {
      input.dispose();
      return null;
    }
    const firstTimestamp = await track.getFirstTimestamp();
    const duration = (await track.computeDuration()) - firstTimestamp;
    if (!(duration > 0)) {
      input.dispose();
      return null;
    }

    const scale = Math.min(
      1,
      Math.max(coverWidth / track.displayWidth, coverHeight / track.displayHeight)
    );
    const sink = new CanvasSink(track, {
      width: Math.max(2, Math.round(track.displayWidth * scale)),
      poolSize: 3,
    });

    let frames: AsyncGenerator<WrappedCanvas, void, unknown> | null = null;
    let current: WrappedCanvas | null = null;
    let upcoming: WrappedCanvas | null = null;
    let lastTimestamp = Infinity;

    return {
      duration,
      async frameAt(time) {
        const timestamp = firstTimestamp + (time % duration);
        if (!frames || timestamp < lastTimestamp) {
          void frames?.return();
          frames = sink.canvases(firstTimestamp);
          current = null;
          upcoming = null;
        }
        lastTimestamp = timestamp;

        while (true) {
          if (!upcoming) {
            const next = await frames.next();
            if (next.done) break;
            upcoming = next.value as WrappedCanvas;
          }
          if (upcoming.timestamp > timestamp + 1e-6) break;
          current = upcoming;
          upcoming = null;
        }
        return current ? current.canvas : null;
      },
      dispose() {
        void frames?.return();
        input.dispose();
      },
    };
  } catch (err) {
    input.dispose();
    throw err;
  }
}

function seekVideo(video: HTMLVideoElement, time: number): Promise<void> {
  if (Math.abs(video.currentTime - time) < 0.001 && video.readyState >= 2) {
    return Promise.resolve();
  }
  return new Promise((resolve) => {
    let settled = false;
    const finish = () => {
      if (settled) return;
      settled = true;
      clearTimeout(timeout);
      video.removeEventListener('seeked', onSeeked);
      resolve();
    };
    const onSeeked = () => {
      setTimeout(finish, 150);
      if ('requestVideoFrameCallback' in video) {
        video.requestVideoFrameCallback(() => finish());
      } else {
        finish();
      }
    };
    const timeout = setTimeout(finish, 3000);
    video.addEventListener('seeked', onSeeked);
    video.currentTime = time;
  });
}

async function openSeekingFrameSource(url: string): Promise<VideoFrameSource | null> {
  const video = document.createElement('video');
  video.muted = true;
  video.playsInline = true;
  video.preload = 'auto';
  if (!url.startsWith('blob:') && !url.startsWith('data:')) {
    video.crossOrigin = 'anonymous';
  }
  video.style.cssText =
    'position:fixed;left:0;top:0;width:1px;height:1px;opacity:0.001;pointer-events:none;z-index:-1;';
  document.body.appendChild(video);
  video.src = url;

  const dispose = () => {
    video.removeAttribute('src');
    video.load();
    video.remove();
  };

  const loaded = await new Promise<boolean>((resolve) => {
    const timeout = setTimeout(() => resolve(false), 15000);
    video.addEventListener(
      'loadeddata',
      () => {
        clearTimeout(timeout);
        resolve(true);
      },
      { once: true }
    );
    video.addEventListener(
      'error',
      () => {
        clearTimeout(timeout);
        resolve(false);
      },
      { once: true }
    );
  });

  const duration = video.duration;
  if (!loaded || !Number.isFinite(duration) || duration <= 0) {
    dispose();
    return null;
  }

  return {
    duration,
    async frameAt(time) {
      await seekVideo(video, time % duration);
      return video;
    },
    dispose,
  };
}

async function openVideoFrameSource(
  url: string,
  coverWidth: number,
  coverHeight: number
): Promise<VideoFrameSource | null> {
  let blobUrl = url;
  try {
    const response = await fetch(url, {
      mode: url.startsWith('blob:') || url.startsWith('data:') ? 'same-origin' : 'cors',
    });
    if (response.ok) {
      const blob = await response.blob();
      blobUrl = URL.createObjectURL(blob);
      const decoded = await openDecodedFrameSource(blob, coverWidth, coverHeight);
      if (decoded) {
        const origDispose = decoded.dispose;
        decoded.dispose = () => {
          try {
            URL.revokeObjectURL(blobUrl);
          } catch {
            // ignore
          }
          origDispose();
        };
        return decoded;
      }
    }
  } catch (err) {
    console.warn('[MP4 export] WebCodecs decoding unavailable, seeking hidden video instead:', err);
  }

  const seekingSource = await openSeekingFrameSource(blobUrl !== url ? blobUrl : url);
  if (seekingSource && blobUrl !== url) {
    const origDispose = seekingSource.dispose;
    seekingSource.dispose = () => {
      try {
        URL.revokeObjectURL(blobUrl);
      } catch {
        // ignore
      }
      origDispose();
    };
  }
  return seekingSource;
}

async function loadImageSafe(src: string): Promise<HTMLImageElement | null> {
  const tryLoad = (url: string) =>
    new Promise<HTMLImageElement | null>((resolve) => {
      const img = new Image();
      if (!url.startsWith('blob:') && !url.startsWith('data:')) {
        img.crossOrigin = 'anonymous';
      }
      img.onload = () => resolve(img);
      img.onerror = () => resolve(null);
      img.src = url;
    });

  const primary = await tryLoad(src || DEFAULT_COVER_IMAGE);
  if (primary && primary.naturalWidth > 0) return primary;
  if (src !== DEFAULT_COVER_IMAGE) {
    return await tryLoad(DEFAULT_COVER_IMAGE);
  }
  return null;
}

function sliceAudioBuffer(buffer: AudioBuffer, startFrame: number, endFrame: number): AudioBuffer {
  const slice = new AudioBuffer({
    length: Math.max(1, endFrame - startFrame),
    numberOfChannels: buffer.numberOfChannels,
    sampleRate: buffer.sampleRate,
  });
  for (let channel = 0; channel < buffer.numberOfChannels; channel++) {
    slice.copyToChannel(buffer.getChannelData(channel).subarray(startFrame, endFrame), channel);
  }
  return slice;
}

async function resolveAacBitrate(buffer: AudioBuffer, requestedBitrate: number): Promise<number> {
  const probe = (bitrate: number) =>
    canEncodeAudio('aac', {
      numberOfChannels: buffer.numberOfChannels,
      sampleRate: buffer.sampleRate,
      quality: new Quality({ bitrate }),
    }).catch(() => false);

  if (await probe(requestedBitrate)) return requestedBitrate;
  const safeBitrate = Math.min(requestedBitrate, NATIVE_AAC_SAFE_BITRATE);
  if (safeBitrate !== requestedBitrate && (await probe(safeBitrate))) return safeBitrate;
  if (!aacEncoderRegistered) {
    const { registerAacEncoder } = await import('@mediabunny/aac-encoder');
    registerAacEncoder();
    aacEncoderRegistered = true;
  }
  return requestedBitrate;
}

interface ExportClipItem {
  track: Track;
  startSec: number;
  endSec: number;
  durationSec: number;
  videoSource: VideoFrameSource | null;
  imageEl: HTMLImageElement | null;
}

export async function exportStudioVideoOffline(
  options: OfflineExportOptions
): Promise<OfflineExportResult> {
  const {
    tracks,
    startIndex,
    allowMultiSlide,
    imageSlideDurationSec,
    aspect,
    quality,
    vizMode,
    paletteIndex,
    visualDna,
    isCarouselMode = false,
    carouselIntervalSec = 10,
    mixEnabled = true,
    isZenMode,
    studioActive,
    layeredBg,
    eqGains,
    volume,
    isMuted,
    studioFrameSnapshot,
    customStageMedia = null,
    coverFrameMotion = 'static',
    coverRotationTarget = 'none',
    showCoverCaption = false,
    orbSnapshots,
    orbViewportWidth,
    orbViewportHeight,
    previewCanvas,
    onProgress,
    signal,
  } = options;

  const dims = getRecordingDimensions(aspect, quality);
  const cap = await resolveOfflineVideoCapability(aspect, quality);
  if (!cap.supported) {
    throw new Error('Offline WebCodecs H.264 encoding is not supported in this browser.');
  }
  const fps = cap.fps;

  let lastProgressMs = 0;
  const reportProgress = (
    progress: number,
    stage: OfflineExportStage,
    force = false
  ) => {
    const now = performance.now();
    if (!onProgress || (!force && now - lastProgressMs < PROGRESS_INTERVAL_MS)) return;
    lastProgressMs = now;
    onProgress({ progress: Math.max(0, Math.min(1, progress)), stage });
  };

  const activeTrack = tracks[startIndex] ?? tracks[0];
  if (!activeTrack) {
    throw new Error('No track selected for export.');
  }

  const sequenceTracks: Track[] = [activeTrack];
  if (
    allowMultiSlide &&
    (activeTrack.mediaType === 'image' || activeTrack.mediaType === 'video')
  ) {
    for (let idx = startIndex + 1; idx < tracks.length; idx++) {
      const candidate = tracks[idx];
      if (candidate.mediaType === 'image' || candidate.mediaType === 'video') {
        sequenceTracks.push(candidate);
      } else {
        break;
      }
    }
  }

  const clips: ExportClipItem[] = [];
  const audioSegments: Array<{ buffer: AudioBuffer | null; durationSec: number }> = [];
  const orbImageMap = new Map<string, { img: HTMLImageElement; ok: boolean }>();
  let customVideoSource: VideoFrameSource | null = null;
  let customImageEl: HTMLImageElement | null = null;
  let customOverlayAudio: AudioBuffer | null = null;
  let output: Output<Mp4OutputFormat, BufferTarget> | null = null;

  const useCustomStageMedia =
    Boolean(customStageMedia) &&
    customStageMedia?.kind !== 'camera' &&
    activeTrack.mediaType !== 'video' &&
    activeTrack.mediaType !== 'image';

  try {
    reportProgress(0, 'preparing', true);
    throwIfAborted(signal);

    // Preload Zen orb cover images if exporting Zen Orbs scene
    if (orbSnapshots && orbSnapshots.length > 0) {
      const uniqueCovers = Array.from(new Set(orbSnapshots.map((s) => s.coverSrc)));
      await Promise.all(
        uniqueCovers.map(async (src) => {
          const img = await loadImageSafe(src);
          if (img) {
            orbImageMap.set(src, { img, ok: img.naturalWidth > 0 });
          }
        })
      );
    }
    const defaultCoverImg = await loadImageSafe(DEFAULT_COVER_IMAGE);
    if (defaultCoverImg) {
      orbImageMap.set(DEFAULT_COVER_IMAGE, {
        img: defaultCoverImg,
        ok: defaultCoverImg.naturalWidth > 0,
      });
    }
    throwIfAborted(signal);

    // Prepare audio + video/image sources for each clip in the sequence
    let timelineCursor = 0;
    for (let i = 0; i < sequenceTracks.length; i++) {
      throwIfAborted(signal);
      const tr = sequenceTracks[i];
      let clipDur = imageSlideDurationSec;
      let videoSource: VideoFrameSource | null = null;
      let imageEl: HTMLImageElement | null = null;
      let clipAudio: AudioBuffer | null = null;

      if (tr.mediaType === 'video') {
        videoSource = await openVideoFrameSource(tr.src, dims.exportWidth, dims.exportHeight);
        if (!videoSource) {
          throw new Error(`Video clip "${tr.title}" could not be decoded for export.`);
        }
        const audioRes = await decodeAndApplyEqAudio(tr.src, eqGains, volume, isMuted, true);
        clipAudio = audioRes.buffer;
        clipDur =
          videoSource.duration > 0
            ? videoSource.duration
            : audioRes.durationSec > 0
            ? audioRes.durationSec
            : tr.durationHint ?? 10;
      } else if (tr.mediaType === 'image') {
        imageEl = await loadImageSafe(tr.cover || tr.src);
        clipDur = tr.durationHint && tr.durationHint > 0 ? tr.durationHint : imageSlideDurationSec;
      } else {
        // Primary Audio track: require full EQ-processed audio decoding (throw OfflineCorsAudioError on CORS block)
        const audioRes = await decodeAndApplyEqAudio(tr.src, eqGains, volume, isMuted, false);
        clipAudio = audioRes.buffer;
        clipDur =
          audioRes.durationSec > 0
            ? audioRes.durationSec
            : tr.durationHint && tr.durationHint > 0
            ? tr.durationHint
            : 30;
        imageEl = await loadImageSafe(tr.cover || DEFAULT_COVER_IMAGE);
      }

      clips.push({
        track: tr,
        startSec: timelineCursor,
        endSec: timelineCursor + clipDur,
        durationSec: clipDur,
        videoSource,
        imageEl,
      });
      audioSegments.push({ buffer: clipAudio, durationSec: clipDur });
      timelineCursor += clipDur;

      reportProgress(
        PREPARE_SHARE * ((i + 1) / sequenceTracks.length),
        'preparing',
        true
      );
    }

    if (useCustomStageMedia && customStageMedia) {
      throwIfAborted(signal);
      if (customStageMedia.kind === 'video') {
        customVideoSource = await openVideoFrameSource(
          customStageMedia.src,
          dims.exportWidth,
          dims.exportHeight
        );
        if (customStageMedia.soundEnabled && customStageMedia.soundVolume > 0) {
          const overlayRes = await decodeAndApplyEqAudio(
            customStageMedia.src,
            [0, 0, 0, 0, 0],
            customStageMedia.soundVolume,
            isMuted,
            true
          );
          customOverlayAudio = overlayRes.buffer;
        }
      } else {
        customImageEl = await loadImageSafe(customStageMedia.src);
      }
    }

    throwIfAborted(signal);

    let soundtrack = concatenateAudioSegments(audioSegments);
    if (soundtrack && customOverlayAudio) {
      soundtrack = mixLoopedOverlayAudio(soundtrack, customOverlayAudio);
    }
    const totalDurationSec = Math.max(0.2, timelineCursor);
    const totalFrames = Math.max(1, Math.round(totalDurationSec * fps));
    const exportDuration = totalFrames / fps;
    const fftSampler = soundtrack ? new OfflineAnalyserSampler(soundtrack, fps) : null;

    // Render canvas matches recording dimensions directly with logical coordinate scaling
    const renderCanvas = document.createElement('canvas');
    renderCanvas.width = dims.exportWidth;
    renderCanvas.height = dims.exportHeight;
    const renderCtx = renderCanvas.getContext('2d', { alpha: false });
    if (!renderCtx) {
      throw new Error('Canvas 2D context is unavailable.');
    }
    const scaleX = dims.exportWidth / dims.logicalWidth;
    const scaleY = dims.exportHeight / dims.logicalHeight;
    renderCtx.imageSmoothingEnabled = true;
    renderCtx.imageSmoothingQuality = 'high';

    output = new Output({
      format: new Mp4OutputFormat({ fastStart: 'in-memory' }),
      target: new BufferTarget(),
    });

    const videoSource = new CanvasSource(renderCanvas, {
      codec: 'avc',
      quality: new Quality({ bitrate: dims.offlineBitrate }),
      latencyMode: 'quality',
    });
    output.addVideoTrack(videoSource, { frameRate: fps });

    let audioSource: AudioBufferSource | null = null;
    if (soundtrack) {
      const audioBitrate = await resolveAacBitrate(soundtrack, dims.audioBitrate);
      audioSource = new AudioBufferSource({
        codec: 'aac',
        quality: new Quality({ bitrate: audioBitrate }),
      });
      output.addAudioTrack(audioSource);
    }

    await output.start();

    const audioFrames = soundtrack
      ? Math.min(soundtrack.length, Math.round(exportDuration * soundtrack.sampleRate))
      : 0;
    let audioCursor = 0;
    const pushAudioUntil = async (time: number) => {
      if (!soundtrack || !audioSource) return;
      const until = Math.min(audioFrames, Math.ceil(time * soundtrack.sampleRate));
      while (audioCursor < until) {
        const end = Math.min(until, audioCursor + soundtrack.sampleRate);
        await audioSource.add(sliceAudioBuffer(soundtrack, audioCursor, end));
        audioCursor = end;
      }
    };

    const sim = createVisualizerSimState(dims.logicalWidth, dims.logicalHeight);
    const studioFrameCopy = studioFrameSnapshot ? cloneStudioFrameState(studioFrameSnapshot) : null;
    const orbsCopy = orbSnapshots && orbSnapshots.length > 0 ? cloneOrbSnapshots(orbSnapshots) : null;
    const prefersReducedMotion =
      typeof window !== 'undefined' &&
      window.matchMedia('(prefers-reduced-motion: reduce)').matches;

    const previewCtx = previewCanvas?.getContext('2d') ?? null;
    let lastPreviewMs = 0;
    let lastYieldMs = performance.now();
    const dt = 1 / fps;

    const validCarouselSec = Math.max(1, carouselIntervalSec || CAROUSEL_INTERVAL_OPTIONS[1]);
    const carouselSteps: Array<{ vizMode: number; paletteIndex: number; visualDna: VisualDNA }> = [
      { vizMode, paletteIndex, visualDna },
    ];
    if (isCarouselMode) {
      const stepCount = Math.max(1, Math.ceil(totalDurationSec / validCarouselSec));
      for (let s = 1; s < stepCount; s++) {
        const prevStep = carouselSteps[s - 1];
        let nextMode = Math.floor(Math.random() * VIZ_MODES.length);
        if (nextMode === prevStep.vizMode) {
          nextMode = (prevStep.vizMode + 1 + Math.floor(Math.random() * 5)) % VIZ_MODES.length;
        }
        let nextPalette = Math.floor(Math.random() * PALETTES.length);
        if (nextPalette === prevStep.paletteIndex) {
          nextPalette = (prevStep.paletteIndex + 1) % PALETTES.length;
        }
        carouselSteps.push({
          vizMode: nextMode,
          paletteIndex: nextPalette,
          visualDna: createRandomVisualDna(nextMode, mixEnabled),
        });
      }
    }

    for (let frame = 0; frame < totalFrames; frame++) {
      throwIfAborted(signal);
      const time = frame / fps;
      await pushAudioUntil(time + 1);

      const carouselStepIdx = isCarouselMode
        ? Math.min(carouselSteps.length - 1, Math.floor(time / validCarouselSec))
        : 0;
      const activeStep = carouselSteps[carouselStepIdx] ?? carouselSteps[0];
      const stepVizMode = activeStep.vizMode;
      const stepPaletteIndex = activeStep.paletteIndex;
      const stepVisualDna = activeStep.visualDna;
      const stepLayeredBg = isCarouselMode
        ? mixEnabled && stepVisualDna.mixLayers.length > 0
        : layeredBg;

      // Resolve active clip at `time`
      const activeClip =
        clips.find((c) => time >= c.startSec && time < c.endSec) ?? clips[clips.length - 1];
      const localTime = Math.max(0, time - activeClip.startSec);

      let mediaSource: CanvasImageSource | null = activeClip.imageEl;
      let mediaWidth = activeClip.imageEl?.naturalWidth ?? 0;
      let mediaHeight = activeClip.imageEl?.naturalHeight ?? 0;

      if (activeClip.videoSource) {
        const vFrame = await activeClip.videoSource.frameAt(localTime);
        if (vFrame) {
          mediaSource = vFrame;
          if (vFrame instanceof HTMLVideoElement) {
            mediaWidth = vFrame.videoWidth;
            mediaHeight = vFrame.videoHeight;
          } else if ('width' in vFrame && 'height' in vFrame) {
            mediaWidth = Number((vFrame as { width: number }).width) || dims.logicalWidth;
            mediaHeight = Number((vFrame as { height: number }).height) || dims.logicalHeight;
          }
        }
      }

      let backdropSource: CanvasImageSource | null = null;
      let backdropWidth = 0;
      let backdropHeight = 0;
      let skipFallbackCenterOrb = false;
      let frameStudioActive =
        studioActive ||
        activeClip.track.mediaType === 'video' ||
        activeClip.track.mediaType === 'image';

      if (useCustomStageMedia && customStageMedia) {
        let customSrc: CanvasImageSource | null = customImageEl;
        let customW = customImageEl?.naturalWidth ?? 0;
        let customH = customImageEl?.naturalHeight ?? 0;

        if (customVideoSource) {
          const cFrame = await customVideoSource.frameAt(time);
          if (cFrame) {
            customSrc = cFrame;
            if (cFrame instanceof HTMLVideoElement) {
              customW = cFrame.videoWidth;
              customH = cFrame.videoHeight;
            } else if ('width' in cFrame && 'height' in cFrame) {
              customW = Number((cFrame as { width: number }).width) || dims.logicalWidth;
              customH = Number((cFrame as { height: number }).height) || dims.logicalHeight;
            }
          }
        }

        if (customSrc && customW > 0 && customH > 0) {
          if (customStageMedia.displayMode === 'frame') {
            mediaSource = customSrc;
            mediaWidth = customW;
            mediaHeight = customH;
            frameStudioActive = true;
          } else {
            backdropSource = customSrc;
            backdropWidth = customW;
            backdropHeight = customH;
            skipFallbackCenterOrb = true;
          }
        }
      }

      if (fftSampler) {
        fftSampler.sampleAt(time, sim.freqData, sim.timeData);
      } else {
        fillIdleSpectrum(
          sim.freqData,
          sim.timeData,
          time,
          stepVisualDna.dynamics,
          stepVisualDna.seed,
          prefersReducedMotion
        );
      }

      const isCustomFrameActive = Boolean(
        useCustomStageMedia && customStageMedia?.displayMode === 'frame'
      );
      const isCustomCleanBackdrop = Boolean(
        useCustomStageMedia &&
          customStageMedia?.displayMode === 'backdrop' &&
          customStageMedia.backdropOverlay === 'clean'
      );
      const effectiveFrameMotion: FrameMotionMode = isCustomFrameActive
        ? customStageMedia!.frameMotion
        : coverFrameMotion;
      const effectiveRotationTarget: FrameRotationTarget = isCustomFrameActive
        ? customStageMedia!.frameRotationTarget
        : coverRotationTarget;
      const captionVisible =
        showCoverCaption &&
        !isCustomFrameActive &&
        !isCustomCleanBackdrop &&
        activeClip.track.mediaType !== 'video' &&
        activeClip.track.mediaType !== 'image';

      renderCtx.setTransform(scaleX, 0, 0, scaleY, 0, 0);
      stepAndRenderVisualizerFrame({
        ctx: renderCtx,
        sim,
        width: dims.logicalWidth,
        height: dims.logicalHeight,
        nowSec: time,
        dtSec: dt,
        isPlaying: true,
        vizMode: stepVizMode,
        paletteIndex: stepPaletteIndex,
        visualDna: stepVisualDna,
        isZenMode,
        isRecordArmed: true,
        isRecording: true,
        studioActive: frameStudioActive,
        layeredBg: stepLayeredBg,
        prefersReducedMotion,
        studioFrame: studioFrameCopy,
        frameMotion: effectiveFrameMotion,
        frameRotationTarget: effectiveRotationTarget,
        isEditingStudioFrame: false,
        mediaSource,
        mediaWidth,
        mediaHeight,
        coverCaptionTitle: captionVisible ? activeClip.track.title : null,
        coverCaptionArtist: captionVisible ? activeClip.track.artist : null,
        backdropSource,
        backdropWidth,
        backdropHeight,
        backdropOverlay:
          useCustomStageMedia && customStageMedia?.displayMode === 'backdrop'
            ? customStageMedia.backdropOverlay
            : undefined,
        skipFallbackCenterOrb,
        showStudioOverlay: false,
        orbSnapshots: orbsCopy,
        orbViewportWidth,
        orbViewportHeight,
        resolveOrbImage: (src) => orbImageMap.get(src) ?? orbImageMap.get(DEFAULT_COVER_IMAGE) ?? null,
        advanceOrbPhysics: true,
      });

      await videoSource.add(time, dt);

      const now = performance.now();
      if (previewCtx && previewCanvas && now - lastPreviewMs > PREVIEW_INTERVAL_MS) {
        lastPreviewMs = now;
        previewCtx.drawImage(renderCanvas, 0, 0, previewCanvas.width, previewCanvas.height);
      }
      reportProgress(
        PREPARE_SHARE + (1 - PREPARE_SHARE - FINALIZE_SHARE) * ((frame + 1) / totalFrames),
        'rendering'
      );
      if (now - lastYieldMs > YIELD_INTERVAL_MS) {
        await yieldToEventLoop();
        lastYieldMs = performance.now();
      }
    }

    await pushAudioUntil(Infinity);
    throwIfAborted(signal);
    reportProgress(1 - FINALIZE_SHARE * 0.5, 'finalizing', true);

    videoSource.close();
    audioSource?.close();
    await output.finalize();

    const buffer = output.target.buffer;
    if (!buffer || buffer.byteLength === 0) {
      throw new Error('MP4 muxer produced an empty file.');
    }
    reportProgress(1, 'finalizing', true);

    return {
      blob: new Blob([buffer], { type: 'video/mp4' }),
      fileExtension: 'mp4',
      durationSec: exportDuration,
      width: dims.exportWidth,
      height: dims.exportHeight,
      fps,
      hasAudio: Boolean(audioSource),
    };
  } catch (err) {
    if (output && output.state !== 'finalized' && output.state !== 'canceled') {
      await output.cancel().catch(() => {});
    }
    throw err;
  } finally {
    try {
      customVideoSource?.dispose();
    } catch {
      // ignore cleanup error
    }
    for (const clip of clips) {
      try {
        clip.videoSource?.dispose();
      } catch {
        // ignore cleanup error
      }
    }
  }
}
