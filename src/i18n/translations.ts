const TRANSLATIONS: Record<SupportedLang, Translations> = {
  en,
  ru,
  uk,
  es,
  fr,
  de,
  it,
  pt,
  zh,
  ja,
  ko,
  tr,
  pl,
  ar,
  hi,
  uz,
  kk,
};

const LANG_ALIASES: Record<string, SupportedLang> = {
  kz: 'kk',
  in: 'hi',
};

export function detectBrowserLanguage(): SupportedLang {
  if (typeof navigator === 'undefined') return 'en';
  const candidates =
    navigator.languages && navigator.languages.length > 0
      ? navigator.languages
      : [navigator.language || 'en'];

  for (const raw of candidates) {
    const base = raw.toLowerCase().split(/[-_]/)[0];
    if (base in TRANSLATIONS) {
      return base as SupportedLang;
    }
    if (base in LANG_ALIASES) {
      return LANG_ALIASES[base];
    }
  }
  return 'en';
}

export function getTranslations(lang?: SupportedLang): Translations {
  const active = lang ?? detectBrowserLanguage();
  return TRANSLATIONS[active] ?? en;
}
